/* Lay a text out the way the firmware lays out one frame: honour the
 * persisted alignment, uppercase, and show only the page that is up (a
 * message carries literal backslash-n page markers). */
function padRow(text, width, alignment) {
	var page = String(text == null ? "" : text).split("\\n")[0].toUpperCase();
	if (page.length > width) page = page.slice(0, width);
	var spare = width - page.length;
	var left = alignment === "right" ? spare
		: alignment === "center" ? Math.floor(spare / 2) : 0;
	return " ".repeat(left) + page + " ".repeat(spare - left);
}

/* A duration, never a clock time: the age is meaningful on a board that has
 * never reached an NTP server. */
function relativeAge(seconds) {
	var s = Math.max(0, Math.floor(Number(seconds) || 0));
	if (s < 45) return "just now";
	if (s < 3600) return Math.round(s / 60) + " min ago";
	if (s < 86400) {
		var h = Math.floor(s / 3600);
		var m = Math.round((s % 3600) / 60);
		return m ? h + " h " + m + " m ago" : h + " h ago";
	}
	var d = Math.round(s / 86400);
	return d + (d === 1 ? " day ago" : " days ago");
}

/* The wire vocabulary of DisplaySource (#403) in the owner's words. Renaming
 * a key here is a UI change; renaming one in the firmware is a wire change. */
var SOURCE_WORDS = {
	web: { who: "Your message", how: "sent from a browser" },
	mqtt: { who: "Home Assistant", how: "sent over MQTT" },
	clock: { who: "Clock", how: "kept by this controller", when: "updates each minute" },
	leader: { who: "The leader", how: "handed to this row by " },
	none: { who: "Nothing", how: "the wall is blank", when: "" }
};

function sourceLine(source, ageSeconds, leaderName) {
	var w = SOURCE_WORDS[source] || SOURCE_WORDS.none;
	var how = w.how;
	if (source === "leader") how += leaderName || "the leader of this wall";
	return {
		who: w.who,
		how: how,
		when: w.when !== undefined ? w.when : relativeAge(ageSeconds)
	};
}

var ROLE_WORDS = {
	"headless-spare": "spare",
	"headless-backup": "standing by",
	"headless-monitor": "monitor"
};

/* What this controller is doing, in words, plus how loudly to say it.
 * kind "" is quiet and uncoloured — a wall where everything is fine should
 * be typographic. Order is precedence: the most consequential thing wins. */
function controllerState(c) {
	if (c.rescue) return { label: "in rescue", kind: "bad" };
	if (c.updating) return { label: "taking firmware", kind: "busy" };
	if (c.unitReflash && c.unitReflash.active) {
		return { label: "flashing its units", kind: "busy" };
	}
	if (c.degraded) return { label: "not answering", kind: "bad" };
	if (c.renderStuck) return { label: "content stuck", kind: "bad" };
	if (c.clustered && !c.self && !c.joined) return { label: "not joined", kind: "bad" };
	if (c.faulty > 0) {
		return {
			label: c.faulty + (c.faulty === 1 ? " unit faulty" : " units faulty"),
			kind: "bad"
		};
	}
	/* #385's suspect tier is a quiet one by design — failing contacts that
	   have not yet gone silent are reported, never alarmed. */
	if (c.suspect) return { label: "contact failing", kind: "" };
	if (!c.width) return { label: ROLE_WORDS[c.role] || "drives no row", kind: "" };
	return { label: "ok", kind: "" };
}

/* A controller is addressed by the row it drives; one that drives none is
 * addressed by its name, never by a row it does not have. */
function controllerWhere(c) {
	if (c.width > 0 && c.row !== null && c.row !== undefined) return "row " + c.row;
	return c.name || "this box";
}

var TROUBLE_SENTENCE = {
	"in rescue": "is in rescue",
	"taking firmware": "is taking firmware",
	"flashing its units": "is flashing its units",
	"not answering": "is not answering",
	"content stuck": "is showing stale content",
	"not joined": "has not joined"
};

/* The single line home keeps for hardware. Present in every state; it merely
 * stops being quiet when something needs you. */
function controllersLine(list) {
	var worst = null;
	list.forEach(function (c) {
		var st = controllerState(c);
		if (st.kind === "") return;
		if (!worst || (worst.st.kind !== "bad" && st.kind === "bad")) {
			worst = { c: c, st: st };
		}
	});
	if (!worst) return { text: list.length + " · all well", kind: "" };
	var say = TROUBLE_SENTENCE[worst.st.label] || ("has " + worst.st.label);
	return { text: controllerWhere(worst.c) + " " + say, kind: worst.st.kind };
}

function capacityLine(rows) {
	if (!rows.length) return "This box drives no flaps, so there is nothing to write to.";
	var total = rows.reduce(function (n, r) { return n + r.width; }, 0);
	if (rows.length === 1) return total + " characters fit on this wall.";
	return total + " characters fit on this wall — " + rows.map(function (r) {
		return r.width + " on row " + r.index;
	}).join(", ") + ".";
}

/* Fan-out prefix. "" is this box; anything else is a LAN member addressed
 * straight from the browser, exactly as the member pills did before. */
function controllerBase(c) {
	return c.self || !c.host ? "" : "http://" + c.host;
}

function memberIsSelf(m, s, leading) {
	/* A leader knows its own row from the empty host. A follower reading the
	   leader's digest cannot — that `self` flag belongs to the leader — so it
	   finds itself by the row and width it was given. */
	if (leading) return m.self === true;
	return m.row === s.clusterRow && m.width === s.unitCount;
}

function memberController(m, i, s, leading) {
	var self = memberIsSelf(m, s, leading);
	return {
		id: self ? "self" : (m.host || ("row" + m.row + "-" + i)),
		host: m.host || "",
		self: self,
		name: self ? (s.effectiveDeviceName || "This box") : (m.host || ""),
		plat: m.plat || (self ? s.plat : ""),
		rev: m.rev || "",
		row: m.row,
		col: m.col || 0,
		width: m.width || 0,
		joined: m.joined !== false,
		degraded: !!m.degraded,
		suspect: !!m.suspect,
		renderStuck: !!m.renderStuck,
		updating: !!m.updating,
		updateBlocked: !!m.updateBlocked,
		rescue: !!m.rescue,
		faulty: m.faulty || 0,
		detected: m.detected,
		faultMask: m.faultMask || "",
		wear: !!m.wear,
		role: m.role || "display",
		clustered: true,
		unitReflash: { active: false, done: 0, total: 0 }
	};
}

function selfController(s, reflash) {
	return {
		id: "self",
		host: "",
		self: true,
		name: s.effectiveDeviceName || "This box",
		plat: s.plat || "",
		rev: s.version || "",
		row: 0,
		col: 0,
		width: s.unitCount || 0,
		joined: true,
		degraded: false,
		suspect: false,
		renderStuck: false,
		updating: false,
		updateBlocked: false,
		rescue: false,
		faulty: 0,
		detected: s.detectedUnitCount,
		faultMask: "",
		wear: false,
		role: s.deviceRole || "display",
		clustered: false,
		unitReflash: reflash
	};
}

function reflashFacts(block) {
	var state = block && block.state ? String(block.state) : "idle";
	return {
		active: state !== "idle" && state !== "",
		done: (block && Number(block.done)) || 0,
		total: (block && Number(block.total)) || 0
	};
}

function segmentText(rowText, col, width) {
	var slice = rowText.slice(col, col + width);
	while (slice.length < width) slice += " ";
	return slice;
}

/* The wall as two object types: rows of flaps, and boxes running firmware.
 *
 * input: { settings, status, rows, text, reflash, selfFaulty }
 *   settings  this box's /settings
 *   status    /cluster/status while leading, the digest's status while
 *             following, null/disabled when standalone
 *   rows      pre-positioned wall rows (SSE while leading, digest while
 *             following); null falls back to this box's own text
 */
function wallModel(input) {
	var s = input.settings || {};
	var status = input.status;
	var leading = !!s.clusterLeading;
	var members = status && status.enabled && status.members && status.members.length
		? status.members : null;
	var reflash = reflashFacts(input.reflash);

	var controllers = members
		? members.map(function (m, i) { return memberController(m, i, s, leading); })
		: [selfController(s, reflash)];
	if (members) {
		controllers.forEach(function (c) {
			if (c.self) {
				c.unitReflash = reflash;
				if (input.selfFaulty !== undefined) c.faulty = Number(input.selfFaulty) || 0;
			}
		});
	} else if (input.selfFaulty !== undefined) {
		controllers[0].faulty = Number(input.selfFaulty) || 0;
	}

	var byRow = {};
	controllers.forEach(function (c) {
		/* A controller with no row renders nothing on the board. */
		if (!(c.width > 0)) return;
		(byRow[c.row] = byRow[c.row] || []).push(c);
	});

	var wallRows = Object.keys(byRow).map(Number).sort(function (a, b) {
		return a - b;
	}).map(function (idx) {
		var segs = byRow[idx].slice().sort(function (a, b) { return a.col - b.col; });
		var width = segs.reduce(function (n, c) {
			return Math.max(n, c.col + c.width);
		}, 0);
		var supplied = input.rows && input.rows[idx] !== undefined
			? String(input.rows[idx]).toUpperCase() : null;
		var rowText = supplied !== null ? supplied
			: (segs.some(function (c) { return c.self; })
				? padRow(input.text, width, s.alignment)
				: " ".repeat(width));
		var states = segs.map(controllerState);
		return {
			index: idx,
			width: width,
			silent: states.some(function (st) { return st.kind === "bad"; }),
			busy: states.some(function (st) { return st.kind === "busy"; }),
			flag: states.filter(function (st) { return st.kind !== ""; })[0] || null,
			segments: segs.map(function (c) {
				return {
					controller: c,
					col: c.col,
					width: c.width,
					text: segmentText(rowText, c.col, c.width)
				};
			})
		};
	});

	return {
		controllers: controllers,
		rows: wallRows,
		/* One flap size for the whole wall: every row draws at the widest
		   row's cell size, so five units next to sixteen read as five units
		   next to sixteen. */
		width: wallRows.reduce(function (n, r) { return Math.max(n, r.width); }, 0)
	};
}

/* The member table's wire string: host|row|col|width;… — an empty host is
 * the leader's own row. */
function clusterTableSpec(members) {
	return members.map(function (m) {
		return [m.host || "", m.row, m.col, m.width].join("|");
	}).join(";");
}

function parseClusterTable(members) {
	return (members || []).map(function (m) {
		return { host: m.host || "", row: m.row, col: m.col, width: m.width };
	});
}

/* Turn "what the drum is actually showing" into a new stored offset.
 * A drum showing one flap past the target over-rotated by one flap, so it
 * must stop one flap earlier — the correction is subtracted. */
function correctedOffset(currentOffset, realityIndex, expectIndex) {
	return currentOffset - Math.round((realityIndex - expectIndex) * STEPS_PER_FLAP);
}

function letterToIndex(ch) {
	if (!ch) return -1;
	if (ch === "ä" || ch === "Ä") ch = "$";
	else if (ch === "ö" || ch === "Ö") ch = "&";
	else if (ch === "ü" || ch === "Ü") ch = "#";
	else ch = ch.toUpperCase();
	return CALIBRATION_LETTERS.indexOf(ch);
}

