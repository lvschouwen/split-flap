/* ---------- the one status line ---------- */

function say(node, message, kind, hideAfterMs) {
	if (!node) return;
	node.textContent = message;
	node.className = "note" + (kind ? " " + kind : "");
	node.hidden = false;
	if (node._timer) clearTimeout(node._timer);
	if (hideAfterMs) {
		node._timer = setTimeout(function () { node.hidden = true; }, hideAfterMs);
	}
}

function statusLine() {
	var p = el("p", "note");
	p.hidden = true;
	p.setAttribute("role", "status");
	return p;
}

/* ---------- the one confirm-then-act ---------- */

/* Every consequential action goes through here, so "nothing happens without
 * asking you first" is a property of the code, not of each call site. */
function confirmThen(question, run) {
	if (question && !confirm(question)) return false;
	run();
	return true;
}

/* ---------- the one wire layer ---------- */

function getJson(url) {
	return fetch(url, { cache: "no-store" }).then(function (r) {
		if (!r.ok) throw new Error("HTTP " + r.status);
		return r.json();
	});
}

function postText(url) {
	return fetch(url, { method: "POST" }).then(function (r) {
		return r.text().then(function (t) {
			if (!r.ok) throw new Error(t.trim() || ("HTTP " + r.status));
			return t.trim();
		});
	});
}

/* Per-field save against the omnibus POST / (provided-field gating): only
 * the fields named here are applied, so each control saves on its own. */
function postFields(base, fields) {
	var body = new URLSearchParams();
	Object.keys(fields).forEach(function (k) { body.append(k, fields[k]); });
	body.append("ajax", "1");
	return fetch((base || "") + "/", { method: "POST", body: body })
		.then(function (r) {
			return r.text().then(function (t) {
				if (!r.ok) throw new Error(t.trim() || ("HTTP " + r.status));
				return t.trim();
			});
		});
}

function query(params) {
	var q = Object.keys(params || {}).map(function (k) {
		return encodeURIComponent(k) + "=" + encodeURIComponent(params[k]);
	}).join("&");
	return q ? "?" + q : "";
}

/* ---------- the one async-op poll ---------- */

var OP_REASONS = {
	pending: "still queued — the display is busy; check the units in a moment",
	expired: "outcome unknown (a later operation replaced it) — re-read the units"
};

/* Unit operations are queued for the display task and answered later against
 * the {"seq":N} they hand back. One implementation, used by every op on
 * every screen, local or fanned out to a member. */
function runOp(base, path, params) {
	return fetch((base || "") + path + query(params), { method: "POST" })
		.then(function (r) {
			return r.text().then(function (t) {
				if (!r.ok) throw new Error(t.trim() || ("HTTP " + r.status));
				return JSON.parse(t);
			});
		})
		.then(function (d) { return pollOp(base, d.seq, 60); });
}

function pollOp(base, seq, remaining) {
	return getJson((base || "") + "/unit/op-result?seq=" + seq)
		.catch(function () { return null; })
		.then(function (res) {
			if ((!res || res.state === "pending") && remaining > 0) {
				return new Promise(function (resolve) {
					setTimeout(function () {
						resolve(pollOp(base, seq, remaining - 1));
					}, 500);
				});
			}
			if (!res) throw new Error("no answer from the box");
			if (res.state === "ok") return res;
			throw new Error(OP_REASONS[res.state]
				|| ((res.reason || "failed") + (res.detail ? " (" + res.detail + ")" : "")));
		});
}

/* ---------- the one upload-with-progress ---------- */

/* Images are hashed in the browser and the hash rides the query string: the
 * handler verifies the upload arrived intact before committing it. */
function uploadImage(base, path, file, onProgress) {
	return new Promise(function (resolve, reject) {
		var reader = new FileReader();
		reader.onerror = function () { reject(new Error("could not read the file")); };
		reader.onload = function () {
			var md5 = SparkMD5.ArrayBuffer.hash(reader.result);
			var rev = file.name.match(/-([0-9a-f]{7,40}(?:-dirty)?)(?:-[a-z0-9]+)?\.bin$/i);
			var url = (base || "") + path + "?md5=" + md5
				+ (rev ? "&v=" + encodeURIComponent(rev[1]) : "");
			var form = new FormData();
			form.append("firmware", file);
			var xhr = new XMLHttpRequest();
			xhr.open("POST", url);
			xhr.upload.onprogress = function (e) {
				if (e.lengthComputable && onProgress) onProgress(e.loaded / e.total);
			};
			xhr.onreadystatechange = function () {
				if (xhr.readyState !== 4) return;
				if (xhr.status === 200) resolve(xhr.responseText.trim());
				else if (xhr.status === 0) reject(new Error("lost the connection mid-upload"));
				else reject(new Error("HTTP " + xhr.status + ": " + xhr.responseText.trim()));
			};
			xhr.send(form);
		};
		reader.readAsArrayBuffer(file);
	});
}

/* A file picker plus its own progress bar and status line. */
function uploadControl(opts) {
	var wrap = el("div", "upload");
	var picker = input(opts.id, "file");
	picker.accept = ".bin,application/octet-stream";
	var status = statusLine();
	var bar = el("div", "bar");
	var fill = el("div", "fill");
	bar.appendChild(fill);
	bar.hidden = true;
	var go = button("btn primary small", opts.label, function () {
		var file = picker.files[0];
		if (!file) return say(status, "Pick a " + opts.expect + " first.", "bad", 5000);
		if (opts.nameCheck && !opts.nameCheck.test(file.name)) {
			return say(status, file.name + " is not a " + opts.expect + ".", "bad", 8000);
		}
		confirmThen(opts.confirm(file), function () {
			go.disabled = picker.disabled = true;
			bar.hidden = false;
			fill.style.width = "0%";
			say(status, "Hashing the image…", "pending");
			uploadImage(opts.base, opts.path, file, function (f) {
				fill.style.width = Math.round(f * 100) + "%";
				say(status, "Uploading… " + Math.round(f * 100) + "%", "pending");
			}).then(function (text) {
				say(status, text || "Done.", "ok");
				if (opts.done) opts.done();
			}).catch(function (e) {
				say(status, "Upload failed — " + e.message, "bad");
			}).then(function () {
				go.disabled = picker.disabled = false;
				bar.hidden = true;
			});
		});
	});
	wrap.appendChild(picker);
	wrap.appendChild(go);
	wrap.appendChild(bar);
	wrap.appendChild(status);
	return wrap;
}

/* ---------- one sparkline ---------- */

function sparkline(values) {
	var svg = document.createElementNS("http://www.w3.org/2000/svg", "svg");
	svg.setAttribute("viewBox", "0 0 100 28");
	svg.setAttribute("preserveAspectRatio", "none");
	svg.setAttribute("class", "spark");
	svg.setAttribute("aria-hidden", "true");
	var points = (values || []).filter(function (v) { return typeof v === "number"; });
	if (points.length < 2) return svg;
	var lo = Math.min.apply(null, points);
	var hi = Math.max.apply(null, points);
	var span = hi - lo || 1;
	var d = points.map(function (v, i) {
		var x = (i / (points.length - 1)) * 100;
		var y = 27 - ((v - lo) / span) * 26;
		return (i ? "L" : "M") + x.toFixed(1) + " " + y.toFixed(1);
	}).join(" ");
	var path = document.createElementNS("http://www.w3.org/2000/svg", "path");
	path.setAttribute("d", d);
	svg.appendChild(path);
	return svg;
}

