function platLabel(plat) {
	return plat === "esp01" ? "ESP-01" : plat === "esp32s3" ? "ESP32-S3" : plat || "";
}

function drawList() {
	var kit = clear(byId("kit"));
	var withRow = 0;
	view.wall.controllers.forEach(function (c) {
		if (c.width > 0) withRow++;
		var st = controllerState(c);
		var b = el("button", "box");
		b.type = "button";
		b.appendChild(el("span", "name", c.name || c.host || "This box"));
		b.appendChild(el("span", "state" + (st.kind ? " " + st.kind : ""), st.label));
		b.appendChild(el("span", "drives", c.width > 0
			? "Row " + c.row + " — " + c.width + (c.width === 1 ? " unit" : " units")
			: "Drives no row"));
		b.appendChild(el("span", "meta", [c.host || "this box", platLabel(c.plat), c.rev]
			.filter(Boolean).join(" · ")));
		b.addEventListener("click", function () {
			view.from = "list";
			navigate("#c/" + encodeURIComponent(c.id));
		});
		kit.appendChild(b);
	});
	var n = view.wall.controllers.length;
	var without = n - withRow;
	byId("list-sub").textContent = n === 1 ? "One box on this wall."
		: n + " boxes on this wall — " + withRow
			+ (withRow === 1 ? " drives a row" : " drive a row")
			+ (without ? ", " + without + (without === 1 ? " does not." : " do not.") : ".");
}

/* ==========================================================================
 * navigation — the screen lives in the hash, so a phone's back button walks
 * back out of a unit instead of leaving the console
 * ========================================================================== */

function show(screen) {
	var changed = view.screen !== screen;
	view.screen = screen;
	["home", "list", "ctrl", "unit"].forEach(function (s) {
		byId("s-" + s).hidden = s !== screen;
	});
	if (!changed) return;
	var h = document.querySelector("#s-" + screen + " h1");
	if (h) h.focus();
	window.scrollTo(0, 0);
}

function navigate(hash) {
	if (location.hash === hash) route();
	else location.hash = hash;
}

function route() {
	var h = location.hash.replace(/^#/, "");
	if (h === "controllers") {
		drawList();
		show("list");
		return;
	}
	var unit = h.match(/^u\/(.+)\/(\d+)$/);
	if (unit) {
		var uc = controllerById(decodeURIComponent(unit[1]));
		if (uc) {
			openUnit(uc.id, Number(unit[2]));
			return;
		}
	}
	if (h.indexOf("c/") === 0) {
		var id = decodeURIComponent(h.slice(2));
		if (controllerById(id)) {
			openController(id);
			return;
		}
	}
	show("home");
}

function openController(id) {
	var c = controllerById(id);
	if (!c) return;
	view.ctrlId = id;
	byId("ctrl-back-lbl").textContent = view.from === "list" ? "Controllers" : "The wall";
	drawController(c);
	show("ctrl");
	loadController(c).then(function () {
		if (view.screen === "ctrl" && view.ctrlId === id) {
			drawController(controllerById(id) || c);
		}
	});
}

function openUnit(ctrlId, index) {
	var c = controllerById(ctrlId);
	if (!c) return;
	view.ctrlId = ctrlId;
	view.unitIndex = index;
	drawUnit(c, index);
	show("unit");
	loadController(c).then(function () {
		if (view.screen === "unit" && view.unitIndex === index) {
			drawUnit(controllerById(ctrlId) || c, index);
		}
	});
}

/* ==========================================================================
 * refresh
 * ========================================================================== */

/* Keep an open detail screen live, but never while it is being used —
 * redrawing rebuilds its controls, which would stomp a half-typed value. */
function redrawDetailIfIdle() {
	var screen = byId("s-" + view.screen);
	if (screen.contains(document.activeElement)) return;
	var c = controllerById(view.ctrlId);
	if (!c) return;
	var wasScreen = view.screen;
	var wasUnit = view.unitIndex;
	loadController(c).then(function () {
		if (view.screen !== wasScreen || view.ctrlId !== c.id) return;
		if (screen.contains(document.activeElement)) return;
		if (wasScreen === "unit") drawUnit(c, wasUnit);
		else drawController(c);
	});
}

function refresh() {
	return getJson("/settings").then(function (s) {
		view.settings = s;
		byId("offline").hidden = true;
		var next = s.clusterLeading ? getJson("/cluster/status")
			: s.clusterState && s.clusterState !== "standalone" ? getJson("/cluster/digest")
				: Promise.resolve(null);
		return Promise.all([
			next.catch(function () { return null; }),
			getJson("/units/health").catch(function () { return null; })
		]);
	}).then(function (r) {
		var wire = r[0];
		if (wire && wire.status) {
			/* A follower reads the leader's digest: the wall and every member
			   come from there, so the same renderer draws both sides. */
			view.status = wire.status;
			if (wire.rows) view.rows = wire.rows;
		} else {
			view.status = wire;
		}
		if (r[1]) view.units = r[1];
		rebuildWall();
		hydrateNames();
		drawHome();
		if (view.screen === "list") drawList();
		if (view.screen === "ctrl" || view.screen === "unit") redrawDetailIfIdle();
	}).catch(function () {
		byId("offline").hidden = false;
	});
}

function openStream() {
	if (!window.EventSource) return;
	var stream = new EventSource("/events");
	stream.addEventListener("display", function (e) {
		var d = JSON.parse(e.data);
		view.text = d.text || "";
		view.source = d.source || "none";
		view.sourceAge = d.sourceAge || 0;
		/* Rows arrive on the stream only while this box leads. A clustered
		   follower's wall comes from the leader's digest, so leave those
		   alone; only a standalone box collapses back to its own row. */
		if (d.rows) view.rows = d.rows;
		else if (view.settings && !view.settings.clusterLeading
			&& (view.settings.clusterState || "standalone") === "standalone") {
			view.rows = null;
		}
		rebuildWall();
		drawHome();
	});
}

function loadTimezones() {
	if (view.tz) return Promise.resolve(view.tz);
	return getJson("/tz.json").then(function (t) {
		view.tz = t;
		return t;
	}).catch(function () { return null; });
}

function init() {
	byId("send").addEventListener("click", sendMessage);
	byId("stop").addEventListener("click", blankWall);
	byId("msg").addEventListener("keydown", function (e) {
		if (e.key === "Enter" && !byId("send").disabled) sendMessage();
	});
	byId("hw").addEventListener("click", function () { navigate("#controllers"); });
	byId("list-back").addEventListener("click", function () { navigate("#"); });
	byId("ctrl-back").addEventListener("click", function () {
		navigate(view.from === "list" ? "#controllers" : "#");
	});
	byId("unit-back").addEventListener("click", function () {
		navigate("#c/" + encodeURIComponent(view.ctrlId));
	});
	window.addEventListener("hashchange", route);

	refresh().then(function () {
		route();
		openStream();
	});
	/* The stream carries every text change; this is the fallback that notices
	   a controller going quiet, and the only thing that ticks the age. */
	setInterval(refresh, 5000);
	setInterval(drawSource, 1000);
}

if (typeof document !== "undefined") {
	if (document.readyState === "loading") {
		document.addEventListener("DOMContentLoaded", init);
	} else {
		init();
	}
}

