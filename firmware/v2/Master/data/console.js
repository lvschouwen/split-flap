/* Wall Console (#399) — the console, and the only UI.
 *
 * The page is the wall, not an admin panel with a preview on it. Design in
 * docs/superpowers/specs/2026-07-26-web-ui-2026-wall-console-design.md; the
 * two rules it calls load-bearing are enforced here:
 *
 *   - Settings live next to the thing they affect. Name, time zone, role,
 *     broker and firmware belong to the box; speed, line-up, mode and width
 *     to the row; calibration and reflash to the units. There is deliberately
 *     no settings screen collecting them away from what they change.
 *   - State changes density and attention, never what exists. Every row a
 *     controller drives stays on the board whatever has gone wrong with it,
 *     still holding its text; a controller that drives NO row never appears
 *     as an empty row, because an empty row is a lie about the hardware.
 *
 * Four object levels: wall -> controllers -> one controller -> one unit.
 * This file owns the model, the shared mechanisms and the first two levels;
 * console-detail.js owns the last two.
 *
 * Everything above the "DOM" banner is pure and node-testable — see
 * tests/console_pure.test.mjs, which pins both rules. Everything below it
 * touches the document and is proven on the bench.
 *
 * One implementation per affordance (#398): showing a status, confirming a
 * consequential action, running a {"seq":N} unit op, uploading an image with
 * progress, drawing a fact list. If you find yourself writing a second, the
 * first one is in this file.
 */

/* Firmware constants — the alphabet, the geometry of a drum turn, the unit
   status-flag bits — arrive in `SFP`, generated by build_assets.py straight
   from the headers that own them (constants.js). The console holds NO copy
   of any of it: a value that exists twice eventually disagrees with itself,
   and this console describes hardware, where disagreeing is expensive.
   Under node it is a module rather than a global. */
if (typeof SFP === "undefined" && typeof require === "function") {
	var SFP = require("./constants.js");
}

