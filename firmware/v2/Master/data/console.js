function glyphToWire(text) {
	return text.replace(/ä/gi, "$").replace(/ö/gi, "&").replace(/ü/gi, "#");
}

function el(tag, cls, text) {
	var n = document.createElement(tag);
	if (cls) n.className = cls;
	if (text !== undefined && text !== null) n.textContent = text;
	return n;
}

function clear(node) {
	while (node.firstChild) node.removeChild(node.firstChild);
	return node;
}

function byId(id) {
	return document.getElementById(id);
}

/* A key/value fact list. rows are [key, value, note, kind]; every value is a
 * text node, so a device name or a member host can never be markup. */
function factList(rows) {
	var wrap = el("div", "facts");
	rows.forEach(function (r) {
		if (!r) return;
		var f = el("div", "fact");
		f.appendChild(el("span", "k", r[0]));
		var v = el("span", "v" + (r[3] ? " " + r[3] : ""));
		v.appendChild(document.createTextNode(String(r[1])));
		if (r[2]) v.appendChild(el("small", null, r[2]));
		f.appendChild(v);
		wrap.appendChild(f);
	});
	return wrap;
}

